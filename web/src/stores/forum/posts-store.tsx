import type { User } from "../auth-store";

export enum PostStatus {
    UnderReview,
    Approved,
    Answered,
    Archived,
    Deleted,
}

export interface Comment {
    id: string,
    body: string,
    status: PostStatus,
    author: User,
    postId: string,
    createdAt: Date,
    updatedAt: Date,
}

export interface Post {
    id: string,
    slug: string,
    title: string,
    status: PostStatus,
    body: string,
    author: User,
    isMainPost: true,
    comments: Comment[],
    createdAt: Date,
    updatedAt: Date,
}

